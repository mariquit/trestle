import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { build } from "esbuild";

const { metafile } = await build({
  absWorkingDir: import.meta.dirname,
  entryPoints: ["cli.ts"],
  outfile: "bundle/lint.mjs",
  platform: "node",
  target: "node24",
  format: "esm",
  bundle: true,
  minify: true,
  metafile: true,
  banner: { js: "// Copyright (c) 2026 John Anthony Mariquit <john@mariquit.com>\n// SPDX-License-Identifier: Apache-2.0\n// Generated by npm run build. Do not edit. Bundled dependencies: see THIRD-PARTY-LICENSES.txt." },
});

const packages = new Set(Object.keys(metafile.inputs).flatMap((path) => {
  const match = path.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//);
  return match ? [match[1]] : [];
}));
const licenses = [...packages].sort().map((path) => {
  const root = join(import.meta.dirname, path);
  const { name, version } = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
  const files = readdirSync(root).filter((file) => /^(licen[cs]e|copying|notice)(\.|$)/i.test(file));
  if (!files.length) throw new Error(`Missing license for ${name}@${version}`);
  return `${name}@${version}\n\n${files.map((file) => readFileSync(join(root, file), "utf8").trimEnd()).join("\n\n")}`;
});
writeFileSync(join(import.meta.dirname, "bundle/THIRD-PARTY-LICENSES.txt"), licenses.join("\n\n----\n\n") + "\n");
